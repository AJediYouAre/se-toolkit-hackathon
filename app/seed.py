def seed():
    Base.metadata.create_all(bind=engine)
    db = SessionLocal()
    try:
        # Check if already seeded
        existing = db.query(User).filter(User.username == "demo").first()
        if existing:
            print("Seed data already exists. Skipping.")
            return

        user = User(username="demo", hashed_password=pwd_context.hash("demo123"))
        db.add(user)
        db.commit()
        db.refresh(user)

        for r in SAMPLE_RECIPES:
            recipe = Recipe(
                title=r["title"],
                ingredients=r["ingredients"],
                instructions=r["instructions"],
                image_url=r["image_url"],
                user_id=user.id,
            )
            db.add(recipe)

        db.commit()
        print(f"Created user 'demo' with password 'demo123' and {len(SAMPLE_RECIPES)} recipes.")
    finally:
        db.close()


if __name__ == "__main__":
    seed()